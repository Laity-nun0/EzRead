"use strict";
const fs = require("node:fs"), path = require("node:path"), vm = require("node:vm"), assert = require("node:assert/strict");
const state = { settings: {}, reader: { id: "paper", pages: [{number: 1}], blocks: [{id: "old", page: 1, text: "source", translation: "译文", text_override: "revision", note: "note"}], text_annotations: [{id: "annotation"}], text_revision_history: [{id: "revision"}] } };
const nodes = new Map();
const style = {setProperty() {}};
const divider = {setAttribute() {}, hidden: false};
const pane = {hidden: false};
const layout = {style, classList: {toggle(name, value) { this[name] = value; }}};
nodes.set("#reader-layout", layout); nodes.set("#reader-divider", divider); nodes.set(".translation-pane", pane);
const context = {state, console, $: selector => nodes.get(selector), readerPdfLayoutResize() {}};
vm.createContext(context);
for (const file of ["reader.js", "reader-layout.js"]) vm.runInContext(fs.readFileSync(path.join(__dirname, "../static", file), "utf8"), context);
const before = JSON.stringify(state.reader);
context.readerApplyLayout(); assert.equal(pane.hidden, true); assert.equal(divider.hidden, true); assert.equal(layout.classList["reader-original-only"], true);
state.reader.pdf_layout_translation = {current: {id: "submitted"}};
context.readerApplyLayout(); assert.equal(pane.hidden, false); assert.equal(divider.hidden, false); assert.equal(layout.classList["reader-original-only"], false);
delete state.reader.pdf_layout_translation;
assert.equal(JSON.stringify(state.reader), before, "Reading layout does not mutate source, translations, annotations or revisions.");
let citation;
context.setReaderPage = (page, sync) => {citation = [page, sync];};
context.selectBlock("old", true); assert.deepEqual(citation, [1, true]);
const source = fs.readFileSync(path.join(__dirname, "../static/reader.js"), "utf8");
assert.doesNotMatch(source, /正文文本|英文原文|修订历史|readerBindTextSelection|function renderBlock|function openBlockEditor/);
const css = fs.readFileSync(path.join(__dirname, "../static/reader.css"), "utf8");
assert.match(css, /reader-layout\.reader-original-only[^}]*grid-template-rows: minmax\(0, 1fr\)/);
console.log("PDF reader layout checks passed: full-width original, automatic dual pane, hidden divider, preserved historical data and citation page compatibility.");
